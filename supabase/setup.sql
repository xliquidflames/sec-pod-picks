-- ---- Weekly picks: SEC football, NFL and SEC basketball ----
-- One row per person per week. picks holds { "<ESPN game id>": "<team>",
-- "lock_matchup_key": "<game id>" }. Hosts' rows (SEC football only) have
-- is_host = true and can be edited from the host page.

create table if not exists public.picks (
  id bigint generated by default as identity primary key,
  user_name text not null,
  week_number integer not null,
  is_host boolean not null default false,
  picks jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.nfl_picks (like public.picks including all);
create table if not exists public.hoops_picks (like public.picks including all);

-- One entry per name per week, ignoring capitalization.
create unique index if not exists picks_one_per_week on public.picks (lower(user_name), week_number);
create unique index if not exists nfl_picks_one_per_week on public.nfl_picks (lower(user_name), week_number);
create unique index if not exists hoops_picks_one_per_week on public.hoops_picks (lower(user_name), week_number);

-- Anyone can read picks and submit their own. Only host rows can be
-- changed afterward (the host page updates them).
alter table public.picks enable row level security;
alter table public.nfl_picks enable row level security;
alter table public.hoops_picks enable row level security;

create policy "Anyone can read picks" on public.picks for select using (true);
create policy "Anyone can submit picks" on public.picks for insert with check (true);
create policy "Hosts can update their picks" on public.picks for update using (is_host) with check (is_host);

create policy "Anyone can read NFL picks" on public.nfl_picks for select using (true);
create policy "Anyone can submit NFL picks" on public.nfl_picks for insert with check (true);

create policy "Anyone can read hoops picks" on public.hoops_picks for select using (true);
create policy "Anyone can submit hoops picks" on public.hoops_picks for insert with check (true);

grant select, insert, update on public.picks to anon, authenticated;
grant select, insert on public.nfl_picks to anon, authenticated;
grant select, insert on public.hoops_picks to anon, authenticated;

-- ---- March Madness brackets ----

create table if not exists public.brackets (
  id bigint generated by default as identity primary key,
  user_name text not null,
  season integer not null,
  picks jsonb not null,
  tiebreaker integer,
  created_at timestamptz not null default now()
);

create unique index if not exists brackets_one_per_name on public.brackets (lower(user_name), season);

alter table public.brackets enable row level security;
create policy "Anyone can read brackets" on public.brackets for select using (true);
create policy "Anyone can submit a bracket" on public.brackets for insert with check (true);
grant select, insert on public.brackets to anon, authenticated;

-- ---- Saved copies for the Edge Functions ----
-- Series history, team stat ranks and the YouTube episode list are saved
-- here so the free outside services are asked as little as possible. No
-- policies on purpose: only the Edge Functions (server side) use it.

create table if not exists public.series_cache (
  matchup text primary key,
  data jsonb not null,
  fetched_at timestamptz not null default now()
);

alter table public.series_cache enable row level security;
