-- ---- Weekly picks: SEC football, NFL and SEC basketball ----
-- One row per person per week. picks holds { "<ESPN game id>": "<team>",
-- "lock_matchup_key": "<game id>" }. Hosts' rows (SEC football only) have
-- is_host = true and are saved only through save_host_picks below.

create table if not exists public.picks (
  id bigint generated by default as identity primary key,
  user_name text not null,
  week_number integer not null,
  is_host boolean not null default false,
  picks jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.nfl_picks (like public.picks including all);
create table if not exists public.hoops_picks (like public.picks including all);

-- One entry per name per week, ignoring capitalization.
create unique index if not exists picks_one_per_week on public.picks (lower(user_name), week_number);
create unique index if not exists nfl_picks_one_per_week on public.nfl_picks (lower(user_name), week_number);
create unique index if not exists hoops_picks_one_per_week on public.hoops_picks (lower(user_name), week_number);

-- Anyone can read picks and submit a listener entry. Nobody can change or
-- delete one from the website, or submit as a host.
alter table public.picks enable row level security;
alter table public.nfl_picks enable row level security;
alter table public.hoops_picks enable row level security;

create policy "Anyone can read picks" on public.picks for select using (true);
create policy "Listeners can submit picks" on public.picks for insert with check (is_host = false);
create policy "Anyone can read NFL picks" on public.nfl_picks for select using (true);
create policy "Listeners can submit NFL picks" on public.nfl_picks for insert with check (is_host = false);
create policy "Anyone can read hoops picks" on public.hoops_picks for select using (true);
create policy "Listeners can submit hoops picks" on public.hoops_picks for insert with check (is_host = false);

revoke update, delete, truncate on public.picks, public.nfl_picks, public.hoops_picks from anon, authenticated;
grant select, insert on public.picks, public.nfl_picks, public.hoops_picks to anon, authenticated;

-- Every new entry gets the database's own clock as its time, so nobody can
-- backdate one. The site ignores picks made after kickoff.
create or replace function public.stamp_created_at() returns trigger
language plpgsql as $$
begin
  new.created_at := now();
  return new;
end $$;

create trigger stamp_created_at before insert on public.picks for each row execute function public.stamp_created_at();
create trigger stamp_created_at before insert on public.nfl_picks for each row execute function public.stamp_created_at();
create trigger stamp_created_at before insert on public.hoops_picks for each row execute function public.stamp_created_at();

-- The host PIN lives here, where the site can't read it. To change it later:
-- update public.host_pin set pin = 'NEW-PIN';
create table if not exists public.host_pin (pin text not null);
alter table public.host_pin enable row level security;
revoke all on public.host_pin from anon, authenticated;
insert into public.host_pin (pin) values ('NEW-PIN-HERE');

-- Host picks are saved only through this, which checks the PIN first.
-- A wrong PIN waits 2 seconds, so guessing is slow.
create or replace function public.save_host_picks(p_pin text, p_name text, p_week integer, p_picks jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from host_pin where upper(pin) = upper(trim(p_pin))) then
    perform pg_sleep(2);
    raise exception 'Invalid Host Security PIN';
  end if;
  update picks set picks = p_picks, created_at = now()
    where lower(user_name) = lower(p_name) and week_number = p_week and is_host;
  if not found then
    insert into picks (user_name, week_number, is_host, picks) values (p_name, p_week, true, p_picks);
  end if;
end $$;

revoke all on function public.save_host_picks(text, text, integer, jsonb) from public;
grant execute on function public.save_host_picks(text, text, integer, jsonb) to anon, authenticated;

-- ---- March Madness brackets ----

create table if not exists public.brackets (
  id bigint generated by default as identity primary key,
  user_name text not null,
  season integer not null,
  picks jsonb not null,
  tiebreaker integer,
  created_at timestamptz not null default now()
);

create unique index if not exists brackets_one_per_name on public.brackets (lower(user_name), season);

alter table public.brackets enable row level security;
create policy "Anyone can read brackets" on public.brackets for select using (true);
create policy "Anyone can submit a bracket" on public.brackets for insert with check (true);
grant select, insert on public.brackets to anon, authenticated;

-- ---- Saved copies for the Edge Functions ----
-- Series history, team stat ranks and the YouTube episode list are saved
-- here so the free outside services are asked as little as possible. No
